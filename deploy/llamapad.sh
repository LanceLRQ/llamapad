# 部署目录候选：--dir > LLAMAPAD_HOME（命令入口设置）> 脚本自身所在目录
home_candidate() {
  if [ -n "$OPT_DIR" ]; then
    abs_path "$OPT_DIR"
  elif [ -n "${LLAMAPAD_HOME:-}" ]; then
    abs_path "$LLAMAPAD_HOME"
  elif [ -n "$LP_SELF" ] && [ -f "$LP_SELF" ]; then
